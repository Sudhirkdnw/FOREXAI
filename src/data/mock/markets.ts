// Helper to generate realistic candle sequence around a base price
function generateCandles(basePrice: number, count: number, trendBias: number, volatility: number): Candle[] {
  const candles: Candle[] = [];
  let currentClose = basePrice - (trendBias * count * 0.0003);
  const now = new Date(2026, 8, 24, 15, 30); // Sep 24, 2026

  for (let i = 0; i < count; i++) {
    const timeOffset = (count - 1 - i) * 60; // minutes
    const candleTime = new Date(now.getTime() - timeOffset * 60000);
    const timeStr = `${candleTime.getHours().toString().padStart(2, '0')}:${candleTime.getMinutes().toString().padStart(2, '0')}`;

    const step = (Math.random() - 0.48 + trendBias * 0.15) * volatility;
    const open = Number((currentClose).toFixed(basePrice > 50 ? 2 : 4));
    const close = Number((open + step).toFixed(basePrice > 50 ? 2 : 4));
    const high = Number((Math.max(open, close) + Math.random() * volatility * 0.8).toFixed(basePrice > 50 ? 2 : 4));
    const low = Number((Math.min(open, close) - Math.random() * volatility * 0.8).toFixed(basePrice > 50 ? 2 : 4));
    const volume = Math.floor(1200 + Math.random() * 4500 + (Math.abs(close - open) / (volatility || 1)) * 3000);

    currentClose = close;

    // Approximated EMA 20 & EMA 50
    const ema20 = Number((close * 0.9992 + (trendBias > 0 ? -0.0006 : 0.0006)).toFixed(basePrice > 50 ? 2 : 4));
    const ema50 = Number((close * 0.9975 + (trendBias > 0 ? -0.0014 : 0.0014)).toFixed(basePrice > 50 ? 2 : 4));
    const rsi = Number(Math.min(85, Math.max(25, 52 + trendBias * 12 + (Math.random() * 10 - 5))).toFixed(1));
    const macd = Number((0.0008 * trendBias + (Math.random() * 0.0004 - 0.0002)).toFixed(5));
    const macdSignal = Number((macd * 0.75).toFixed(5));
    const macdHist = Number((macd - macdSignal).toFixed(5));

    candles.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
      ema20,
      ema50,
      rsi,
      macd,
      macdSignal,
      macdHist,
    });
  }
  return candles;
}

